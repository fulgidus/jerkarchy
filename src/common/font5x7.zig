/// True if character `ch` (any case) has the pixel at column x, row y.
pub fn pixel(ch: u8, x: usize, y: usize) bool {
    const up = if (ch >= 'a' and ch <= 'z') ch - 32 else ch;
    for (glyphs) |g| {
        if (g.ch == up) return g.rows[y][x] == '#';
    }
    return if (up == '?') false else pixel('?', x, y);
}

/// True if every character of `s` has a glyph (so validation can refuse others).
pub fn supported(s: []const u8) bool {
    outer: for (s) |ch| {
        const up = if (ch >= 'a' and ch <= 'z') ch - 32 else ch;
        for (glyphs) |g| if (g.ch == up) continue :outer;
        return false;
    }
    return true;
}

/// Width in font pixels of `s` with one blank column between characters.
pub fn textWidth(s: []const u8) usize {
    return if (s.len == 0) 0 else s.len * (w + 1) - 1;
}
